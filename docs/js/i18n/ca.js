/** Look up a UI string and fill `{name}` placeholders. Unknown keys return the key itself. */
export function t(key, vars = {}) {
  const str = ca[key];
  if (str === undefined) {
    console.warn(`i18n: missing key "${key}"`);
    return key;
  }
  return str.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

/** True when a key exists (used for optional labels such as unknown rarities). */
export function has(key) {
  return key in ca;
}
